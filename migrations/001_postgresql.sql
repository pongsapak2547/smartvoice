CREATE TABLE calls (
                id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                filename          TEXT NOT NULL,
                file_hash         TEXT NOT NULL UNIQUE,
                file_path         TEXT NOT NULL,
                transcript        TEXT,
                summary           TEXT,
                sentiment         TEXT CHECK(sentiment IN ('positive','neutral','negative')),
                topic             TEXT,
                speaker_mapping   TEXT,
                agent_performance TEXT,
                keywords          TEXT,
                anomaly_detected  INTEGER DEFAULT 0,
                anomaly_reason    TEXT,
                status            TEXT NOT NULL DEFAULT 'uploaded'
                                    CHECK(status IN ('uploaded','processing','done','error')),
                error_msg         TEXT,
                created_at        TEXT NOT NULL,
                updated_at        TEXT NOT NULL
            , brand_mentions TEXT, platform_mentions TEXT, processing_step TEXT, sentiment_reason TEXT, anomaly_severity TEXT, customer_phone TEXT, case_id INTEGER, uploaded_by TEXT, uploaded_by_role TEXT, topic_detail TEXT);

CREATE TABLE customers (
                id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                first_name     TEXT NOT NULL,
                last_name      TEXT NOT NULL,
                phone          TEXT UNIQUE,
                email          TEXT,
                gender         TEXT,
                date_of_birth  TEXT,
                address        TEXT,
                subdistrict    TEXT,
                district       TEXT,
                city_province  TEXT,
                country        TEXT DEFAULT 'Thailand',
                postcode       TEXT,
                created_at     TEXT NOT NULL
            , deleted_at TEXT, deleted_by TEXT, nick_name TEXT, channel TEXT);

CREATE TABLE warranty_registrations (
                id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                registration_no         TEXT UNIQUE NOT NULL,
                customer_id             INTEGER REFERENCES customers(id),
                channel                 TEXT,
                certificate_no          TEXT,
                category                TEXT,
                brand                   TEXT,
                model                   TEXT,
                size                    TEXT,
                sku                     TEXT,
                serial_no               TEXT,
                label_no                TEXT,
                warranty_period_months  INTEGER DEFAULT 120,
                date_of_purchase        TEXT,
                date_of_delivery        TEXT,
                purchase_channel        TEXT,
                order_number            TEXT,
                expiry_date             TEXT,
                remark                  TEXT,
                created_at              TEXT NOT NULL
            , deleted_at TEXT, deleted_by TEXT, hidden_with_customer INTEGER DEFAULT 0, ref_id TEXT, so_number TEXT, status TEXT DEFAULT 'active', cancelled_at TEXT, cancelled_by TEXT, proof_path TEXT);

CREATE TABLE call_customer_links (
                id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                call_id      INTEGER NOT NULL REFERENCES calls(id) ON DELETE CASCADE,
                customer_id  INTEGER NOT NULL REFERENCES customers(id),
                warranty_id  INTEGER REFERENCES warranty_registrations(id),
                matched_by   TEXT DEFAULT 'manual',
                created_at   TEXT NOT NULL
            );

CREATE TABLE users (
                id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username       TEXT NOT NULL UNIQUE,
                display_name   TEXT NOT NULL,
                role           TEXT NOT NULL,
                password_hash  TEXT NOT NULL,
                is_active      INTEGER NOT NULL DEFAULT 1,
                created_at     TEXT NOT NULL,
                updated_at     TEXT NOT NULL,
                last_login_at  TEXT
            );

CREATE TABLE audit_log (
                id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                actor         TEXT,
                actor_role    TEXT,
                action        TEXT NOT NULL,
                entity        TEXT NOT NULL,
                entity_id     INTEGER,
                entity_label  TEXT,
                changes       TEXT,
                created_at    TEXT NOT NULL
            );

CREATE TABLE cases (
                id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_id   INTEGER REFERENCES customers(id),
                subject       TEXT NOT NULL,
                status        TEXT NOT NULL DEFAULT 'open'
                                CHECK(status IN ('open','closed','follow_up')),
                created_at    TEXT NOT NULL,
                updated_at    TEXT NOT NULL
            , assignee_username TEXT, assignee_name TEXT, assigned_at TEXT, closed_by TEXT, closed_at TEXT);

CREATE TABLE sales_orders (
            id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            so_number    TEXT NOT NULL UNIQUE,
                document_date TEXT,
                order_date TEXT,
                shipment_date TEXT,
                promised_delivery_date TEXT,
                due_date TEXT,
                currency TEXT,
                sales_type TEXT,
                purchasing_type TEXT,
                salesperson TEXT,
                external_doc TEXT,
                credit_term TEXT,
                customer_po_no TEXT,
                sell_to_no TEXT,
                sell_to_name TEXT,
                sell_to_address TEXT,
                sell_to_contact TEXT,
                sell_to_phone TEXT,
                ship_to_name TEXT,
                ship_to_address TEXT,
                ship_to_contact TEXT,
                ship_to_phone TEXT,
                ship_to_email TEXT,
                total DOUBLE PRECISION,
                discount DOUBLE PRECISION,
                net_amount DOUBLE PRECISION,
                vat DOUBLE PRECISION,
                grand_total DOUBLE PRECISION,
                remark TEXT,
            customer_id  INTEGER REFERENCES customers(id),
            created_at   TEXT NOT NULL,
            updated_at   TEXT NOT NULL,
            created_by   TEXT,
            deleted_at   TEXT,
            deleted_by   TEXT
        );

CREATE TABLE sales_order_lines (
            id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sales_order_id           INTEGER NOT NULL REFERENCES sales_orders(id) ON DELETE CASCADE,
            line_no                  INTEGER,
            item_no                  TEXT,
            description              TEXT,
            requested_delivery_date  TEXT,
            uom                      TEXT,
            location                 TEXT,
            quantity                 DOUBLE PRECISION,
            unit_price               DOUBLE PRECISION,
            discount                 DOUBLE PRECISION,
            amount                   DOUBLE PRECISION
        );

CREATE INDEX idx_so_customer ON sales_orders(customer_id);

CREATE INDEX idx_so_ship_phone ON sales_orders(ship_to_phone);

CREATE INDEX idx_so_lines_order ON sales_order_lines(sales_order_id);

CREATE UNIQUE INDEX users_username_lower_unique ON users (lower(username));
